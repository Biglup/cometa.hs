credentialCbor :: IO ()
credentialCbor = do
  key <- require (Credential.keyHashFromBytes (B.replicate 28 7))
  script <- require (Credential.scriptHashFromBytes (B.replicate 28 8))
  forM_ [Credential.KeyCredential key, Credential.ScriptCredential script] $ \credential -> do
    let encoded = Credential.encodeCbor credential
    (Credential.decodeCbor encoded :: Either Error (Credential.Credential Credential.Payment)) @?= Right credential
    (Credential.decodeCbor (B.singleton 0x9f <> B.drop 1 encoded <> B.singleton 0xff) :: Either Error (Credential.Credential Credential.Payment)) @?= Right credential
  forM_ [B.empty, B.pack [0x82, 2, 0x58, 28] <> B.replicate 28 0, B.pack [0x82, 0, 0x41, 0], B.pack [0x82, 0, 0x58, 28] <> B.replicate 28 0 <> B.singleton 0] $ \bytes ->
    assertBool "invalid credential rejected" (isLeft (Credential.decodeCbor bytes :: Either Error (Credential.Credential Credential.Payment)))
